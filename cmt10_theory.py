section("第三部分：Range Accrual 票券的定價邏輯")

print("""
3.1  票息結構的數學表達
───────────────────────────────────────────────────────────
本產品的季度票息現金流為：

    CF_t = FACE × dt_q × C(r_t)

其中票息率函數 C(r_t) 為分段常數：

         ┌  C_high  if r_t ≤ 5.00%           （高息層）
    C(r_t) = │  C_mid   if 5.00% < r_t ≤ 5.25%  （中息層）
         └  0         if r_t > 5.25%           （零息層，觸發障礙）

此結構等同於投資人「賣出」了兩個數位選擇權（Digital Options）：

    C(r_t) = C_high × 𝟏{r_t ≤ 5.00%}
           + C_mid  × 𝟏{5.00% < r_t ≤ 5.25%}

        = C_high × 𝟏{r_t ≤ 5.25%}
        + (C_high - C_mid) × 𝟏{r_t > 5.00%} × 𝟏{r_t ≤ 5.25%}  ← 這一項為負號
        [可以用不同方式分解]

        更直觀的分解：
        = C_high × 𝟏{r_t ≤ 5.00%}  ← 投資人持有的利率看漲數位選擇權
        + C_mid  × 𝟏{5.00%<r_t≤5.25%}  ← 次級保護層

3.2  Range Accrual Bullet 的解析公允價格
───────────────────────────────────────────────────────────
在 Vasicek 模型下，對於無 Callable 特徵的 Range Accrual 票券，
可以解析計算公允價格（不需要蒙地卡羅）：

    PV = Σₜ df(t) × FACE × dt_q × [C_high × Φ(d_H(t)) + C_mid × (Φ(d_M(t)) - Φ(d_H(t)))]
       + FACE × df(T)

其中：
    df(t)  = exp(-disc_r × t)         （平坦折現因子）
    Φ(·)   ：標準常態 CDF
    d_H(t) = (B_H - μ_t) / σ_t        B_H = 5.00%（高息門檻）
    d_M(t) = (B_M - μ_t) / σ_t        B_M = 5.25%（中息門檻）
    μ_t    = r0·e^{-κt} + θ(1-e^{-κt})  （t 時刻的條件期望值）
    σ_t    = σ√((1-e^{-2κt})/(2κ))    （t 時刻的條件標準差）

這個解析公式給出的結果與蒙地卡羅一致，可作為模型驗證的基準。
""")

# ── Analytical price verification ────────────────────────────────────────────
FACE = 100.0
STEPS_YR = 252
T_HIGH_B = 0.0500
T_MID_B  = 0.0525

products = {
    "2yNC1y": dict(maturity=2, no_call=1, cpn_high=0.0510, cpn_mid=0.0445),
    "3yNC1y": dict(maturity=3, no_call=1, cpn_high=0.0665, cpn_mid=0.0555),
}

print("  解析公式驗證（RA Bullet，無 Callable）：")
print(f"  {'產品':<10} {'季配息期':>8} {'解析 PV':>12} {'說明':>30}")
print(f"  {'─'*10} {'─'*8} {'─'*12} {'─'*30}")

for name, spec in products.items():
    T_yr = spec["maturity"]
    n_q  = int(T_yr * 4)
    pv_analytic = 0.0
    for qi in range(1, n_q + 1):
        t = qi * 0.25
        mu_t  = r0 * np.exp(-kappa * t) + theta * (1 - np.exp(-kappa * t))
        sig_t = sigma * np.sqrt((1 - np.exp(-2*kappa*t)) / (2*kappa))
        d_H   = (T_HIGH_B - mu_t) / sig_t
        d_M   = (T_MID_B  - mu_t) / sig_t
        p_hi  = norm.cdf(d_H)
        p_md  = norm.cdf(d_M) - p_hi
        cpn   = spec["cpn_high"] * p_hi + spec["cpn_mid"] * p_md
        df    = np.exp(-disc_r * t)
        pv_analytic += FACE * 0.25 * cpn * df
    pv_analytic += FACE * np.exp(-disc_r * T_yr)
    print(f"  {name:<10} {n_q:>8}    {pv_analytic:>10.4f}  {'（MC 應與此接近）':>30}")


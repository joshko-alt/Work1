section("第二部分：Vasicek 利率模型")

print("""
2.1  隨機微分方程（SDE）
───────────────────────────────────────────────────────────
Vasicek (1977) 模型描述短期利率的動態：

    dr_t = κ(θ - r_t) dt + σ dW_t^Q

其中：
  ─ κ > 0 ：均值回歸速度（Mean-Reversion Speed）
  ─ θ     ：長期均衡利率（Long-Run Mean），風險中性測度下的吸引點
  ─ σ > 0 ：利率波動率（Volatility），年化標準差
  ─ dW_t^Q：在風險中性測度 Q 下的標準布朗運動增量

直觀解釋：
  ─ 若 r_t < θ：漂移項 κ(θ - r_t) > 0，利率被拉升趨向 θ
  ─ 若 r_t > θ：漂移項 κ(θ - r_t) < 0，利率被壓低趨向 θ
  ─ σ 決定圍繞均值的隨機波動幅度

2.2  精確離散解（Exact Discretisation）
───────────────────────────────────────────────────────────
上述 SDE 有精確的解析解，dt = 1/252（每日步長）：

    r_{t+dt} = r_t · e^{-κ·dt}
             + θ · (1 - e^{-κ·dt})
             + σ · √((1 - e^{-2κ·dt}) / (2κ)) · Z

其中 Z ~ N(0,1) 為標準常態隨機數。

【重要】本模型使用精確離散解，而非 Euler-Maruyama 近似（dr ≈ κ(θ-r)dt + σ√dt·Z）
精確解無步長誤差，Euler 近似在 dt 較大時會產生系統性偏誤。

條件分佈（在已知 r_t 下，r_{t+dt} 的分佈）：
    E[r_{t+dt} | r_t] = r_t · e^{-κ·dt} + θ · (1 - e^{-κ·dt})
    Var[r_{t+dt}| r_t] = σ² · (1 - e^{-2κ·dt}) / (2κ)

長期（T → ∞）的穩態分佈（Stationary Distribution）：
    r_∞ ~ N(θ, σ²/(2κ))

2.3  本模型的參數設定與理論依據
───────────────────────────────────────────────────────────
""")

# Parameters
r0    = 0.0430
kappa = 0.20
theta = 0.0430
sigma = 0.0110
disc_r = 0.0430

# Half-life of mean reversion
half_life = np.log(2) / kappa

# Stationary std dev
stat_std = sigma / np.sqrt(2 * kappa)

# 1-year distribution
T1 = 1.0
mean_1y = r0 * np.exp(-kappa * T1) + theta * (1 - np.exp(-kappa * T1))
std_1y  = sigma * np.sqrt((1 - np.exp(-2*kappa*T1)) / (2*kappa))

# 3-year distribution
T3 = 3.0
mean_3y = r0 * np.exp(-kappa * T3) + theta * (1 - np.exp(-kappa * T3))
std_3y  = sigma * np.sqrt((1 - np.exp(-2*kappa*T3)) / (2*kappa))


print("""
1.1  資產定價基本定理（Fundamental Theorem of Asset Pricing）
───────────────────────────────────────────────────────────
在完整市場（Complete Market）且無套利（No-Arbitrage）的假設下，任何衍生性
商品的價格等於其未來現金流在「風險中性測度 Q」下的折現期望值：

    P(t) = E^Q [ e^{-∫_t^T r_s ds} · Payoff_T  |  ℱ_t ]

其中：
  ─ E^Q[·] 為在風險中性測度 Q 下的期望值
  ─ r_s    為 t 到 T 期間的短期利率（此處替換為 10y CMT 作為折現利率）
  ─ e^{-∫r_s ds} 為隨機折現因子（Stochastic Discount Factor）
  ─ ℱ_t   為 t 時刻的市場資訊集合

風險中性測度 Q 的關鍵性質：
  ─ 在 Q 下，所有資產的期望報酬率均等於無風險利率（非真實世界報酬）
  ─ 透過 Girsanov 定理，從真實世界測度 P 轉換到 Q 需加入市場價格風險（λ）
  ─ 市場價格風險 λ 反映投資人的風險偏好，我們的模型隱含 λ = 0（風險中性投資人）

1.2  本模型的簡化：平坦折現率
───────────────────────────────
嚴格的風險中性定價需要：
    P(t) = (1/N) · Σᵢ Σₜ CF_t^i · exp(-∫_0^t r_s^i ds)
                                        ↑
                             路徑 i 的累積折現因子

本模型以「平坦折現率」替代：
    P(t) ≈ (1/N) · Σᵢ Σₜ CF_t^i · exp(-disc_r · t)   (disc_r = 4.30%)

這個簡化的影響：
  ─ 現金流的折現不隨利率路徑變化，等同於假設「殖利率曲線永遠平坦」
  ─ 忽略了利率路徑與折現因子之間的相關性（凸性效果，Convexity Effect）
  ─ 對 2–3 年短期票券而言，誤差通常在 ±0.5 個價格點以內（可接受範圍）
""")


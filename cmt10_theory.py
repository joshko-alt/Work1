section("第四部分：Callable 特徵的定價理論")

print("""
4.1  Callable 票券的正確定價方法
───────────────────────────────────────────────────────────
Callable 票券 = 普通票券 − 發行人所持有的 Bermudan Call Option

    Price(Callable) = Price(Bullet) − Value(Bermudan Call)
    Fair Coupon(Callable) = Fair Coupon(Bullet) + Call Premium

Bermudan Call Option 的特性：
  ─ 發行人在每個季度配息日後（超過 No-Call 期後）可以選擇贖回
  ─ 贖回價格 = Par（100）
  ─ 發行人在「持有成本 > 贖回後再融資成本」時會行使選擇權
  ─ 即：當市場利率下降到低於當前票息率時，發行人會贖回並以更低票息再融資

正確的定價方法：逆向歸納法（Backward Induction）
  ─ 建立利率三叉樹（Trinomial Tree，如 Hull-White 模型）
  ─ 從票券到期日開始，向前倒推每個節點的價值
  ─ 在每個可贖回節點：V(node) = min(Par, Hold Value)   ← 發行人選擇對自己最有利的
  ─ 最終得到 t=0 的公允價值

4.2  本模型的簡化 Callable 邏輯
───────────────────────────────────────────────────────────
本模型使用的啟發式（Heuristic）規則：

    發行人在 Q > no_call_period 時，若 下一期票息 > 當前市場利率 則贖回

    程式碼：
        next_cpn_cost = next_coupon_rate × FACE × dt_q
        funding_cost  = r_t × FACE × dt_q     ← r_t 為當時隨機利率
        will_call     = (next_cpn_cost > funding_cost)
        即：coupon_rate > r_t 時發行人贖回

這個規則的合理性與問題：
  ✓ 方向正確：利率下跌時發行人贖回，利率上升時不贖回
  ✓ 計算簡單，效率高
  ✗ 不是最優行使策略：正確應比較「持有票券的剩餘 PV」vs「立即贖回 = Par」
  ✗ 忽略了遠期利率曲線的影響
  ✗ 忽略了凸性（Convexity）對行使決策的影響

4.3  為什麼模型顯示 Callable 溢價 ≈ 0？
───────────────────────────────────────────────────────────
在我們的平坦折現率框架下，存在一個重要的數學特性：

    對於以平價（Par = 100）發行的固定票息票券：
    若票息 = 折現率，則不論何時提前贖回，PV 均等於 100。

證明（以 2yNC1y 為例）：
    若票息 C = disc_r = 4.30%，則任一時點 t 的剩餘價值：
    PV(t) = C × FACE × Σ_{τ>t} exp(-disc_r·(τ-t)) × dt_q + FACE × exp(-disc_r·(T-t))

    當 C = disc_r 時，這個計算等式永遠等於 FACE = 100（平價特性）。
    因此，在任何節點贖回（得到 Par = 100）與繼續持有（PV = 100）無差異。
    → 行使 Call 選擇權的「價值」在此框架下為 0。

這說明：在平坦折現率模型下，Callable 溢價的正確計算需要更精細的定價框架。

實際市場上，Callable 溢價的合理估計：
    2yNC1y（1y no-call）：約 20–40 bps
    3yNC1y（1y no-call）：約 45–75 bps
    （來源：Hull-White 模型標準定價，以當前利率波動率曲面校準）

4.4  完整定價模型的缺口摘要
───────────────────────────────────────────────────────────
                    本模型         正確方法
    ─────────────────────────────────────────────────
    RA 溢價         ✓ 正確         解析 + MC 均可
    Callable 溢價   ✗ 低估（≈0）   Hull-White tree
    折現利率        平坦 4.30%     OIS 殖利率曲線
    信用利差        未計入         CGMHI CDS spread
    ─────────────────────────────────────────────────
    合計影響：公允票息低估約 25–70 bps
""")

